using Microsoft.Build.Evaluation;

namespace RsGraph.Indexer.Dotnet.Tests;

public sealed class ProjectLoaderTests
{
    public ProjectLoaderTests()
    {
        MsBuildSetup.EnsureRegistered();
    }

    private static string WriteMinimalCsproj(string dir)
    {
        var csprojPath = Path.Combine(dir, "Foo.csproj");
        File.WriteAllText(
            csprojPath,
            """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup>
                <TargetFramework>net8.0</TargetFramework>
                <ImplicitUsings>enable</ImplicitUsings>
              </PropertyGroup>
            </Project>
            """);
        return csprojPath;
    }

    [Fact]
    public void PicksUpTheSdkGeneratedGlobalUsingsFileWhenAlreadyBuiltOnDisk()
    {
        // MSBuild evaluation alone (no build target ever runs — see ProjectLoader's own doc
        // comment) never sees <ImplicitUsings>enable</ImplicitUsings>'s auto-generated
        // GlobalUsings.g.cs file: obj/ is excluded from the default Compile glob, and the SDK
        // only adds it to @(Compile) via a build target, not at evaluation time. If a real
        // `dotnet build`/`restore` already produced it — simulated here by writing the file by
        // hand, exactly matching what a real build leaves behind — Load must still pick it up.
        // Real-world regression: without this, any file relying on an implicit `global using`
        // (a bare `Task<T>` with no explicit `using System.Threading.Tasks;`) silently fails to
        // resolve, and every call/injection through such a type loses its edge with nothing
        // surfaced to the user. It's kept out of CompileItems itself (a separate
        // ImplicitUsingsFile property) so it's fed to the compiler without ever becoming an
        // "owned" file — see LoadedProject.ImplicitUsingsFile and Runner's own use of it.
        var tempDir = Directory.CreateTempSubdirectory("rs-graph-projectloader-test-");
        try
        {
            var csprojPath = WriteMinimalCsproj(tempDir.FullName);
            var intermediateDir = Path.Combine(tempDir.FullName, "obj", "Debug", "net8.0");
            Directory.CreateDirectory(intermediateDir);
            var globalUsingsPath = Path.Combine(intermediateDir, "Foo.GlobalUsings.g.cs");
            File.WriteAllText(
                globalUsingsPath,
                "// <auto-generated/>\nglobal using System;\nglobal using System.Threading.Tasks;\n");

            using var collection = new ProjectCollection();
            var loaded = ProjectLoader.Load(csprojPath, collection);

            Assert.NotNull(loaded);
            Assert.Equal(globalUsingsPath, loaded.ImplicitUsingsFile, ignoreCase: true);
            Assert.DoesNotContain(loaded.CompileItems, p => p.Contains("GlobalUsings"));
        }
        finally
        {
            Directory.Delete(tempDir.FullName, recursive: true);
        }
    }

    [Fact]
    public void DoesNotInventAGlobalUsingsFileThatWasNeverGenerated()
    {
        // A project that hasn't been built yet (no obj/ output at all) must not get a
        // nonexistent path invented for ImplicitUsingsFile.
        var tempDir = Directory.CreateTempSubdirectory("rs-graph-projectloader-test-");
        try
        {
            var csprojPath = WriteMinimalCsproj(tempDir.FullName);

            using var collection = new ProjectCollection();
            var loaded = ProjectLoader.Load(csprojPath, collection);

            Assert.NotNull(loaded);
            Assert.Null(loaded.ImplicitUsingsFile);
        }
        finally
        {
            Directory.Delete(tempDir.FullName, recursive: true);
        }
    }
}
